// Regras permanentes de qualidade visual da Up! Digital.
// Valem para todos os agentes da produção de artes (diretor de arte, arquiteto de layout, crítico e refinador).
// O que é compartilhado entre clientes é o NÍVEL da direção de arte, nunca o estilo de um cliente.

export const QUALITY_RULES = `REGRAS PERMANENTES DE QUALIDADE VISUAL
Composição
- Toda página tem um ponto focal claro e uma ordem de leitura evidente.
- A distribuição dos elementos é intencional. Não centralize tudo por padrão: use assimetria quando ela organiza melhor a leitura.
- Nada de espaço vazio sem função, e nada de aperto. Margens generosas e consistentes.
- Não repita a mesma estrutura por conveniência. Cada página escolhe o layout pelo conteúdo dela.
Fotografia
- A foto faz parte da composição, nunca parece colada sobre o fundo: ela se funde ao fundo ou ocupa a página com intenção.
- Analise o enquadramento antes de posicionar: rosto, olhar, mãos, postura, fundo e espaço negativo. O olhar da pessoa conduz para o texto quando possível.
- Amplie, reduza e recorte com intenção. Evite cortar rosto, mãos, dedos e articulações por acidente.
- Preserve rostos e características físicas. Nunca invente fotos da cliente ou do produto real.
Tipografia
- Hierarquia clara: título, apoio, detalhes. Escala e peso variados.
- Títulos curtos, com boa quebra de linha. Legível na tela de um celular.
- Fontes conforme a identidade do cliente. Letra manuscrita só como destaque pontual e quando combina com a marca.
- Não altere palavras do briefing nem textos obrigatórios.
Fundos e elementos
- Não acrescente faixas brancas, tarjas ou caixas sem função. Caixas e cartões só quando organizam a informação (comparação, cartão de destaque).
- Degradê só onde a leitura precisa, discreto. Sem sombras pesadas.
- Elementos gráficos (ícones, linhas, formas suaves) só quando reforçam a mensagem ou a identidade.
Carrossel
- Unidade visual sem repetição: mesmas cores, fontes e assinatura; composições alternadas.
- Progressão narrativa: capa com gancho, desenvolvimento variado (comparação, lista com ícones, foto ampliada, diagrama, página tipográfica, página de alto contraste), fechamento com chamada para ação.
- Duas páginas seguidas não usam o mesmo layout, salvo motivo forte.
Identidade
- Cada cliente tem cores, fontes, logo, estilo de foto e linguagem gráfica próprios. Não aplique a estética de um cliente em outro.
Texto
- Nunca use travessão nem meia-risca. Nada de hashtags ou emojis na arte.
- Não invente preços, datas, números, promoções, benefícios ou resultados.
- Nada na arte indica automação ou inteligência artificial, e nunca escreva que a imagem é ilustrativa.`;
